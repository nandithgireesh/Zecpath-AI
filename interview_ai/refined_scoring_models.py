"""
Day 42: Refined Scoring Models & Calibrated Data Structures (Deliverable 3)
===========================================================================
Defines the refined parameter weights, cognitive deliberation metrics,
bounded penalty breakdowns, and leveling upgrade telemetry.
"""

from enum import Enum
from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field


class RefinedDecisionTier(str, Enum):
    STRONG_HIRE = "STRONG_HIRE"
    HIRE = "HIRE"
    LEAN_HIRE = "LEAN_HIRE"
    LEAN_NO_HIRE = "LEAN_NO_HIRE"
    NO_HIRE = "NO_HIRE"


class LevelingUpgradeTier(str, Enum):
    STANDARD_PLACEMENT = "STANDARD_PLACEMENT"
    SENIOR_LEAD_UPGRADE = "SENIOR_LEAD_UPGRADE"
    STAFF_PRINCIPAL_UPGRADE = "STAFF_PRINCIPAL_UPGRADE"
    DIRECTOR_EXECUTIVE_UPGRADE = "DIRECTOR_EXECUTIVE_UPGRADE"


class CognitiveDeliberationMetric(BaseModel):
    """Measures answer substance relative to formulation latency."""
    raw_latency_seconds: float
    answer_word_count: int
    deliberation_ratio: float = Field(..., description="Words per second of latency")
    is_analytical_pause: bool = Field(..., description="True if pause preceded deep STAR response")
    hesitation_penalty_discount: float = Field(..., description="Discount applied to latency penalty (0.0 to 0.8)")


class BoundedPenaltyBreakdown(BaseModel):
    """Detailed breakdown of bounded anti-double-dipping deductions."""
    raw_deductions_total: float
    linguistic_penalty: float = Field(..., description="Vagueness + filler penalty capped at 6.0 pts")
    behavioral_penalty: float = Field(..., description="Deflection + contradiction penalty capped at 8.0 pts")
    fallacy_penalty: float = Field(..., description="Logical fallacy penalty capped at 4.0 pts")
    net_bounded_penalty: float = Field(..., description="Total deduction capped at 12.0 pts")
    penalty_damping_applied: float = Field(..., description="Points saved via anti-double-dipping bounding")
    detected_flags: List[str] = Field(default_factory=list)


class RefinedScoreSummary(BaseModel):
    """Complete candidate assessment summary generated by the Refined Scoring Engine."""
    candidate_id: str
    candidate_name: str
    target_role: str
    experience_years: float
    
    # Core Components
    semantic_relevance_score: float = Field(..., ge=0.0, le=100.0)
    communication_score: float = Field(..., ge=0.0, le=100.0)
    composure_confidence_score: float = Field(..., ge=0.0, le=100.0)
    consistency_logic_score: float = Field(..., ge=0.0, le=100.0)
    
    # Synthesized Scores
    raw_composite_score: float = Field(..., ge=0.0, le=100.0)
    net_refined_score: float = Field(..., ge=0.0, le=100.0)
    
    # Refined Sub-Metrics
    deliberation_metrics: CognitiveDeliberationMetric
    penalty_breakdown: BoundedPenaltyBreakdown
    overqualification_index: float
    recommended_leveling_tier: LevelingUpgradeTier
    final_decision: RefinedDecisionTier
    
    # Audit trail
    anomaly_fixes_applied: List[str] = Field(default_factory=list)
    executive_verdict: str
