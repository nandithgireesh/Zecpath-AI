"""
Day 58: Advanced Feature Proposal - Data Models
================================================
Platform: Zecpath Enterprise Automated Hiring Platform
Defines data structures for AI Video Analysis, Emotion Detection,
Real-Time Candidate Feedback, AI Coaching, Interview Analytics Dashboard,
and Scaling AI Roadmaps.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Any, Optional
from enum import Enum
import time


class HorizonLevel(str, Enum):
    HORIZON_1 = "HORIZON_1"  # Near-Term (0 - 6 Months): Real-Time Multimodal & Edge Inference
    HORIZON_2 = "HORIZON_2"  # Mid-Term (6 - 18 Months): Agentic Orchestration & AI Coaching
    HORIZON_3 = "HORIZON_3"  # Long-Term (18 - 36 Months): Autonomous Hiring & Self-Evolving Models


class InnovationArea(str, Enum):
    AI_VIDEO_ANALYSIS = "AI_VIDEO_ANALYSIS"
    EMOTION_DETECTION = "EMOTION_DETECTION"
    REAL_TIME_FEEDBACK = "REAL_TIME_FEEDBACK"
    AI_COACHING_SYSTEM = "AI_COACHING_SYSTEM"
    INTERVIEW_ANALYTICS = "INTERVIEW_ANALYTICS"
    AGENTIC_ORCHESTRATION = "AGENTIC_ORCHESTRATION"


class EmotionState(str, Enum):
    CONFIDENT = "CONFIDENT"
    COMPOSED = "COMPOSED"
    ANALYTICAL = "ANALYTICAL"
    MILD_ANXIETY = "MILD_ANXIETY"
    DISTRACTED = "DISTRACTED"
    DISENGAGED = "DISENGAGED"


@dataclass
class VideoAnalysisTelemetry:
    """Telemetry data extracted from AI computer vision analysis during interviews."""
    candidate_id: str
    timestamp: float = field(default_factory=time.time)
    eye_gaze_stability_pct: float = 88.5
    head_pose_alignment_pct: float = 91.0
    facial_micro_engagement_pct: float = 86.4
    visual_attention_score: float = 89.2
    stress_fidget_count: int = 2
    lighting_and_framing_quality: str = "OPTIMAL"


@dataclass
class EmotionAnalysisTelemetry:
    """Telemetry capturing candidate emotional composure and cognitive load."""
    candidate_id: str
    dominant_emotion: EmotionState = EmotionState.CONFIDENT
    emotional_stability_score: float = 87.5  # 0.0 - 100.0
    composure_index: float = 85.0
    valence_arousal_score: float = 0.72  # Positive engagement
    cognitive_load_estimate: float = 62.0  # Percentage load
    authenticity_confidence: float = 94.2


@dataclass
class RealTimeFeedbackSignal:
    """Low-latency non-intrusive feedback prompt provided to candidate or interviewer."""
    signal_id: str
    target_audience: str  # "CANDIDATE" or "INTERVIEWER"
    signal_type: str  # "PACING_ADVICE", "AUDIO_CLARITY", "DEPTH_PROMPT"
    severity: str  # "INFO", "SUGGESTION", "URGENT"
    message: str
    latency_ms: float = 45.0
    timestamp: float = field(default_factory=time.time)


@dataclass
class CandidateCoachingRecommendation:
    """Actionable improvement suggestions generated by the AI Coaching System."""
    candidate_id: str
    role_category: str
    key_strengths: List[str] = field(default_factory=list)
    growth_areas: List[str] = field(default_factory=list)
    actionable_suggestions: List[str] = field(default_factory=list)
    recommended_learning_resources: List[str] = field(default_factory=list)
    overall_readiness_level: str = "JOB_READY_WITH_MENTORSHIP"


@dataclass
class InterviewAnalyticsMetrics:
    """Aggregated recruitment intelligence metrics for enterprise hiring leaders."""
    total_interviews_analyzed: int = 2450
    avg_interview_duration_mins: float = 42.5
    time_to_hire_reduction_days: float = 14.2  # Reduced from 28 days to 13.8 days
    recruiter_hours_saved_per_hire: float = 18.5
    adverse_impact_ratio: float = 0.94  # Four-Fifths rule certified compliant (>= 0.80)
    candidate_satisfaction_nps: float = 78.4
    interview_completion_rate_pct: float = 96.8
    cost_per_hire_reduction_pct: float = 62.5


@dataclass
class RoadmapMilestone:
    """Milestone specification for scaling the automated hiring AI platform."""
    horizon: HorizonLevel
    phase_title: str
    timeline_window: str
    primary_capabilities: List[str]
    architectural_stack: List[str]
    expected_business_impact: str
    feasibility_and_risk_profile: str
